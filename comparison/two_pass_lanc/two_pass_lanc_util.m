function [QU, Y, iter,k,m,errest] = two_pass_lanc_util(mult,c,normc,options, v1, v2, alphain, betain, H) 

tol = options.tol;
xi = options.xi;
m = options.m;
n = size(c,1);
k = length(xi);
itin = m + 2*k; % number of iterations
errest = [];

% set rational Krylov to compute real basis
options = [];
options.isreal = 1;

% if the first pass has not been computed using full orth because poles or
% extreme eigenvalues are provided, the first pass is performed without
% full orthogonalization
if nargin < 5
    [v1, v2, alpha, beta] = lanczos_coefficients(mult, itin, zeros(n,1), c/normc, 0);
else
    alpha = alphain;
    beta = betain;
end

% T is the tridiagonal matrix generated by Lanczos iterations
T = spdiags([[beta(1:(itin-1));0],alpha, [0;beta(1:(itin-1))]], -1:1, itin,itin);

% U orthonormal basis of Q(T_1, e_1, xi)
U = rational_krylov(T, double(1:itin == 1)', xi, options);

% final projected matrix
ProjMat = U' * T * U;
ProjMat = (ProjMat + ProjMat')/2;

% solve the projected equation
Y = lyap(ProjMat, -normc^2*( U(1,:)' * U(1,:))); 
Y = (Y + Y')/2;

% estimate residual norm
err = sqrt(2)*beta(end) * norm( U(end,:) * Y, 'fro')/normc^2;

% keep track of number of iterations and error
iter = itin;

errest = [errest; [iter, err]];

% if err is larger than tol, proceed with Lanczos
if err >= tol/sqrt(2)
while iter + m < n
    
    % keep track of number of iterations
    iter = iter + m;

    % retrieve the already computed next beta coefficient
    last_beta = beta(end);

    % extend the basis
    [v1, v2, alpha, beta] = lanczos_coefficients(mult, m, v1, v2, beta(end));

    That = spdiags([[beta((1:(m-1)));0],alpha, [0;beta((1:(m-1)))]], -1:1, m,m);
    
    % extend tridiagonal matrix
    T = blkdiag(T,That);
    T(end-m, end-m+1)= last_beta;
    T(end-m+1,end-m) = last_beta;

    % U orthonormal basis of Q(T, e_1, xi)
    U = rational_krylov(T,double(1:iter == 1)',xi, options);

    % final projected matrix
    ProjMat = U' * T * U;
    ProjMat = (ProjMat + ProjMat')/2;

    % solve the projected equation
    Y = lyap(ProjMat, -normc^2*U(1,:)'*U(1,:));
    Y = (Y + Y')/2;

    % estimate residual norm
    err = sqrt(2)*beta(end)*norm( U(end,:) * Y, 'fro')/normc^2;

    errest = [errest; [iter, err]];

    % if norm of the residual is smaller than tolerance, end Lanczos
    if err <= tol/sqrt(2)
        break
    end
end
end

% retrieve all the alpha and beta coefficients
last_beta = beta(end);
alpha = full(diag(T));
beta = full(diag(T, -1));
beta = [beta;last_beta];


% second Lanczos pass: the Lanczos vectors are recomputed (using the stored
% coefficients alpha, beta) in blocks of it = m + k vectors, stored in the 
% last m + k columns of B; QU is accumulated in the first k columns of B
kk = size(U,2);
it = m + k;
bs = 4096; % number of rows per block in the in-place updates
if nargin < 5
    B = zeros(n, kk + it);
    start = 1;
    v1 = zeros(n,1);
    v2 = c/normc;
    b = 0;
else
    % if the first m + 2k iterations were computed with full orthogonalization,
    % they are recomputed with full orthogonalization (all these vectors are needed)
    [B, v1, v2, ~] = full_orth_Arnoldi(mult, itin, c/normc, H);
    for i = 1:bs:n
        rows = i:min(i+bs-1, n);
        B(rows, 1:kk) = B(rows, :) * U(1:itin, :);
    end
    start = itin + 1;
    b = beta(itin);
end

while start <= iter
    stop = min(start + it - 1, iter);
    len = stop - start + 1;
    for i = 1:len
        B(:, kk+i) = v2;
        v = short_recurrence_Lanczos(mult, v1, v2, b, beta(start+i-1), alpha(start+i-1));
        b = beta(start+i-1);
        v1 = v2;
        v2 = v;
    end
    for i = 1:bs:n
        rows = i:min(i+bs-1, n);
        B(rows, 1:kk) = B(rows, 1:kk) + B(rows, kk+1:kk+len) * U(start:stop, :);
    end
    start = stop + 1;
end

QU = B(:, 1:kk);

end


function [v1, v2, alpha, beta] = lanczos_coefficients(mult, m, v1, v2, b)
% m Lanczos iterations (short recurrence) starting from the last two Lanczos
% vectors v1, v2 and the last beta coefficient b; only the coefficients and
% the last two vectors are returned (the basis is not stored)
alpha = zeros(m,1);
beta = zeros(m,1);
for i = 1:m
    [v, alpha(i), beta(i)] = short_recurrence_Lanczos(mult, v1, v2, b);
    b = beta(i);
    v1 = v2;
    v2 = v;
end
end
